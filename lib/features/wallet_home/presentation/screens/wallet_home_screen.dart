  List<double> _walletTrendSeries(
    CurrencyVM currency,
    WalletHomeState state,
    double currentTotalFiat,
  ) {
    final xlmSeries = switch (state.selectedWindow) {
      PriceWindow.h24 => currency.xlmHistory24h,
      PriceWindow.d7 => currency.xlmHistory7,
      PriceWindow.d30 => currency.xlmHistory30,
      PriceWindow.y1 => currency.xlmHistory365,
    };

    final usdcSeries = switch (state.selectedWindow) {
      PriceWindow.h24 => currency.usdcHistory24h,
      PriceWindow.d7 => currency.usdcHistory7,
      PriceWindow.d30 => currency.usdcHistory30,
      PriceWindow.y1 => currency.usdcHistory365,
    };

    final maxLen = [
      xlmSeries.length,
      usdcSeries.length,
    ].reduce((a, b) => a > b ? a : b);
    if (maxLen < 2) return const <double>[];

    final fallbackXlmFiat = currency.xlmToFiat(1.0);
    final fallbackUsdcFiat = currency.usdcToFiat(1.0);

    final series = List<double>.generate(maxLen, (index) {
      final xlmPrice = index < xlmSeries.length && xlmSeries[index].isFinite
          ? xlmSeries[index]
          : fallbackXlmFiat;
      final usdcPrice = index < usdcSeries.length && usdcSeries[index].isFinite
          ? usdcSeries[index]
          : fallbackUsdcFiat;

      return (xlmPrice * state.xlm) + (usdcPrice * state.usdc);
    }, growable: false);

    return series.where((value) => value.isFinite).length >= 2
        ? series
        : const <double>[];
  }

  double _seriesDelta(List<double> series) {
    if (series.length < 2) return 0.0;
    final first = series.first.isFinite ? series.first : 0.0;
    final last = series.last.isFinite ? series.last : 0.0;
    return last - first;
  }

  Future<void> _openRecipientList() async {
    if (!mounted) return;
    final colors = AppColor.of(context);
    final s = ref.read(walletHomeVmProvider).state;
    await Navigator.of(context).push(
      MaterialPageRoute(
        builder: (_) => RecipientListWidget(
          colors: colors,
          fromAddress: s.address,
          xlmBalance: s.xlm,
          usdcBalance: s.usdc,
          showAppBar: true,
        ),
      ),
    );
  }

  Future<void> _autoSaveActiveWalletAddressIfMissing() async {
    if (!mounted) return;
    try {
      await ref.read(walletHomeVmProvider).ensureActiveWalletSavedIfMissing();
    } catch (_) {
      // Silent best-effort; we'll retry on next wallet/home refresh.
    }
  }

  Future<void> _openHeaderScanner() async {
    final vm = ref.read(walletHomeVmProvider);
    final state = vm.state;
    final address = (state.address ?? '').trim();
    if (address.isEmpty) {
      if (!mounted) return;
      showFloatingSnackBar(
        context,
        message: 'Wallet not ready',
        type: SnackBarType.warning,
      );
      return;
    }

    final xlmBalance = state.xlm;
    final usdcBalance = state.usdc;

    try {
      await showTokenSelector(
        context,
        address,
        xlmBalance,
        usdcBalance,
        title: 'Select Coin',
        screenBuilder: (addr, token, balance) => SendScreen(
          address: addr,
          token: token,
          balance: balance,
          autoOpenScanner: true,
          onTransactionCompleted: () => vm.refresh(force: true),
        ),
      );
    } catch (_) {
      if (!mounted) return;
      await Navigator.of(context, rootNavigator: true).push(
        MaterialPageRoute(
          builder: (_) => SendScreen(
            address: address,
            token: 'XLM',
            balance: xlmBalance,
            autoOpenScanner: true,
            onTransactionCompleted: () => vm.refresh(force: true),
          ),
        ),
      );
    } finally {
      if (mounted) {
        await vm.refresh(force: true);
      }
    }
  }

  Future<void> _openP2PMarketplace() async {
    final allowed = await _ensureVerifiedForTradeAccess();
    if (!allowed || !mounted) return;

    Navigator.push(
      context,
      MaterialPageRoute(
        builder: (_) => const MarketOffersScreen(initialType: OfferType.sell),
      ),
    );
  }

  Future<bool> _ensureVerifiedForTradeAccess() async {
    try {
      final allowed = await ref.read(walletHomeVmProvider).hasTradeAccess();
      if (allowed) return true;
    } catch (_) {}

    if (!mounted) return false;
    showFloatingSnackBar(
      context,
      message: 'Verification READY is required for trades',
      type: SnackBarType.warning,
    );
    Navigator.push(
      context,
      MaterialPageRoute(builder: (_) => const VerificationFlowScreen()),
    );
    return false;
  }

  void _onUiEvent(WalletHomeUiEvent e) async {
    if (!mounted) return;

    SnackBarType mapSeverity(UiSeverity s) {
      switch (s) {
        case UiSeverity.success:
          return SnackBarType.success;
        case UiSeverity.warning:
          return SnackBarType.warning;
        case UiSeverity.error:
          return SnackBarType.error;
        case UiSeverity.info:
          return SnackBarType.info;
      }
