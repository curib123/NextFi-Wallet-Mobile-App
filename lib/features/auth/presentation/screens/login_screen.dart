  Future<void> _signInGoogle() async {
    final loginState = ref.read(loginControllerProvider);
    if (loginState.googleLoading || loginState.facebookLoading) return;

    HapticFeedback.lightImpact();

    try {
      final user = await ref
          .read(loginControllerProvider.notifier)
          .signInGoogle();

      if (!mounted) return;

      if (user != null) {
        HapticFeedback.mediumImpact();
        await showLoginSuccessModal(context, user: user);

        if (!mounted) return;

        widget.onLoginSuccess?.call();
        Navigator.pop(context, true);
      } else {
        _snack('Login was cancelled or failed');
      }
    } on AuthException catch (e) {
      if (mounted) _snack(e.message);
    } catch (e) {
      if (mounted) _snack(e.toString());
    }
  }

  void _snack(String msg) {
    if (!mounted) return;
    final colors = AppColor.of(context);
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Text(
          msg,
          style: AppFonts.body(
            color: colors.onPrimary,
            fontWeight: FontWeight.w500,
          ),
        ),
        backgroundColor: colors.error,
        behavior: SnackBarBehavior.floating,
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
        margin: const EdgeInsets.symmetric(horizontal: 24, vertical: 12),
      ),
    );
  }

  Future<void> _openTerms() async {
    final loginState = ref.read(loginControllerProvider);
    await LinkOpener.open(context, loginState.termsUrl, fallbackLabel: 'Terms');
  }

  Future<void> _openPrivacy() async {
    final loginState = ref.read(loginControllerProvider);
    await LinkOpener.open(
      context,
      loginState.privacyUrl,
      fallbackLabel: 'Privacy',
    );
  }

